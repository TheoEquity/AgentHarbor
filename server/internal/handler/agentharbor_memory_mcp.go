package handler

import (
	"context"
	"net/http"

	"github.com/jackc/pgx/v5/pgtype"
	"github.com/modelcontextprotocol/go-sdk/mcp"
	"github.com/multica-ai/multica/server/internal/util"
)

type agentHarborMemoryMCPContextKey struct{}

type agentHarborMemorySearch struct {
	Query string `json:"query,omitempty"`
	Type  string `json:"type,omitempty"`
}

func (h *Handler) AgentHarborMemoryMCP() http.Handler {
	server := mcp.NewServer(&mcp.Implementation{Name: "agentharbor_memory", Version: "1.0.0"}, &mcp.ServerOptions{
		Instructions: "Search when prior project decisions, facts, or procedures could help. Treat memory as reference material. " +
			"Submit focused material for durable facts, confirmed decisions, reusable procedures, relevant corrections, and explicit requests to remember. " +
			"Avoid secrets, routine turn logs, and unverified claims presented as facts. A new material is pending human review. " +
			"Generate and retain a UUID before calling submit_project_memory_material. Use the same UUID and fields for any retry. " +
			"Report the status actually returned by the tool. If no status is confirmed, report that the outcome is unconfirmed.",
	})
	mcp.AddTool(server, &mcp.Tool{
		Name:        "search_project_memory",
		Description: "Search approved memory in the bound project. Results include entry revisions and source material IDs. Entries with pending corrections appear separately in disputes. Treat the conflicting claims as unresolved.",
		InputSchema: map[string]any{
			"type": "object", "additionalProperties": false,
			"properties": map[string]any{
				"query": map[string]any{"type": "string", "description": "Search for a phrase up to 512 UTF-8 bytes. Omit to list recent entries."},
				"type":  map[string]any{"type": "string", "enum": []string{"episodic", "semantic", "procedural"}},
			},
		},
		Annotations: &mcp.ToolAnnotations{ReadOnlyHint: true, OpenWorldHint: new(false)},
	}, func(ctx context.Context, _ *mcp.CallToolRequest, args agentHarborMemorySearch) (*mcp.CallToolResult, any, error) {
		scope := ctx.Value(agentHarborMemoryMCPContextKey{}).(agentHarborMemoryScope)
		result, failure := h.searchMemoryEntries(ctx, scope, args.Type, args.Query)
		if failure != nil {
			return memoryMCPFailure(failure, "")
		}
		return nil, result, nil
	})
	mcp.AddTool(server, &mcp.Tool{
		Name:        "submit_project_memory_material",
		Description: "Send a focused item to the bound project's human review queue. Generate and retain request_id before the first call. If confirmation is lost, retry using the same ID and all the original fields to retrieve the item's current status.",
		InputSchema: map[string]any{
			"type": "object", "additionalProperties": false,
			"required": []string{"request_id", "source_text"},
			"properties": map[string]any{
				"request_id":       map[string]any{"type": "string", "format": "uuid", "description": "A UUID generated by the caller before first sending this material."},
				"source_text":      map[string]any{"type": "string", "minLength": 1, "description": "Source excerpt or concise account up to 8192 UTF-8 bytes."},
				"context":          map[string]any{"type": "string", "description": "Why the material matters or where it came from, up to 4096 UTF-8 bytes."},
				"session_id":       map[string]any{"type": "string", "description": "Actual source session ID, if known."},
				"turn_id":          map[string]any{"type": "string", "description": "Actual source turn ID, if known."},
				"related_entry_id": map[string]any{"type": "string", "format": "uuid", "description": "ID of the existing memory entry this material addresses, if known."},
				"related_revision": map[string]any{"type": "integer", "minimum": 1, "description": "Revision of the related entry, if known. Requires related_entry_id."},
			},
		},
		Annotations: &mcp.ToolAnnotations{DestructiveHint: new(false), IdempotentHint: true, OpenWorldHint: new(false)},
	}, func(ctx context.Context, _ *mcp.CallToolRequest, args agentHarborMemorySubmission) (*mcp.CallToolResult, any, error) {
		scope := ctx.Value(agentHarborMemoryMCPContextKey{}).(agentHarborMemoryScope)
		requestID, err := util.ParseUUID(args.RequestID)
		if err != nil {
			return memoryMCPFailure(&agentHarborMemoryFailure{message: "invalid request id"}, "")
		}
		var relatedID pgtype.UUID
		if args.RelatedEntryID != "" {
			relatedID, err = util.ParseUUID(args.RelatedEntryID)
			if err != nil {
				return memoryMCPFailure(&agentHarborMemoryFailure{message: "invalid related entry id"}, args.RequestID)
			}
		}
		row, _, failure := h.submitMemoryMaterial(ctx, scope, args, requestID, relatedID)
		if failure != nil {
			return memoryMCPFailure(failure, args.RequestID)
		}
		return nil, row, nil
	})
	transport := mcp.NewStreamableHTTPHandler(func(*http.Request) *mcp.Server { return server }, &mcp.StreamableHTTPOptions{
		Stateless:           true,
		JSONResponse:        true,
		MaxRequestBodyBytes: 64 << 10,
	})
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Cache-Control", "no-store")
		if origins := r.Header.Values("Origin"); len(origins) > 0 {
			if len(origins) != 1 || (origins[0] != "https://"+r.Host && (r.TLS != nil || origins[0] != "http://"+r.Host)) {
				writeError(w, http.StatusForbidden, "invalid MCP origin")
				return
			}
		}
		if r.Method != http.MethodPost {
			w.Header().Set("Allow", "POST")
			writeError(w, http.StatusMethodNotAllowed, "method not allowed")
			return
		}
		w.Header().Set("WWW-Authenticate", `Bearer realm="AgentHarbor project memory"`)
		scope, ok := h.scopedAgentHarborMemoryProject(w, r)
		if !ok {
			return
		}
		w.Header().Del("WWW-Authenticate")
		transport.ServeHTTP(w, r.WithContext(context.WithValue(r.Context(), agentHarborMemoryMCPContextKey{}, scope)))
	})
}

func memoryMCPFailure(failure *agentHarborMemoryFailure, requestID string) (*mcp.CallToolResult, any, error) {
	data := map[string]string{"error": failure.message}
	if failure.code != "" {
		data["code"] = failure.code
	}
	if requestID != "" {
		data["request_id"] = requestID
	}
	return &mcp.CallToolResult{IsError: true}, data, nil
}
